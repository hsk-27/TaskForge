-- TaskForge Database Schema Migration V1
-- Compatible with PostgreSQL 12+ and H2 in PostgreSQL mode

CREATE TABLE jobs (
    id VARCHAR(36) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    job_type VARCHAR(50) NOT NULL,
    status VARCHAR(50) NOT NULL,
    priority INT NOT NULL DEFAULT 0,
    payload TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    scheduled_execution_at TIMESTAMP WITH TIME ZONE,
    started_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    attempt_count INT NOT NULL DEFAULT 0,
    max_attempts INT NOT NULL DEFAULT 3,
    last_error_message TEXT,
    worker_id VARCHAR(100),
    execution_duration_ms BIGINT,
    queue_wait_duration_ms BIGINT,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_jobs_status ON jobs(status);
CREATE INDEX idx_jobs_created_at ON jobs(created_at);
CREATE INDEX idx_jobs_priority_created ON jobs(priority DESC, created_at ASC);
CREATE INDEX idx_jobs_scheduled ON jobs(status, scheduled_execution_at);

CREATE TABLE job_attempts (
    id VARCHAR(36) PRIMARY KEY,
    job_id VARCHAR(36) NOT NULL,
    attempt_number INT NOT NULL,
    worker_id VARCHAR(100) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    outcome VARCHAR(50) NOT NULL,
    error_message TEXT,
    duration_ms BIGINT,
    CONSTRAINT fk_attempt_job FOREIGN KEY (job_id) REFERENCES jobs(id) ON DELETE CASCADE
);

CREATE INDEX idx_attempts_job ON job_attempts(job_id, attempt_number);

CREATE TABLE job_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id VARCHAR(36) NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    message TEXT NOT NULL,
    worker_id VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_event_job FOREIGN KEY (job_id) REFERENCES jobs(id) ON DELETE CASCADE
);

CREATE INDEX idx_events_job_created ON job_events(job_id, created_at);
CREATE INDEX idx_events_created ON job_events(created_at DESC);
